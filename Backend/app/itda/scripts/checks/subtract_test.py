def norm(d):
    return {k: [str(x) for x in as_list(v)] for k, v in (d or {}).items()
            if as_list(v)}


bad = []
for name, old, new, msg, want in CASES:
    got, removed = slot_subtract(old, new, msg)
    g, w = norm(got), norm(want)
    ok = g == w
    print(f'{"✅" if ok else "🔴"}  {name}')
    print(f'      🧑 {msg or "(빈 발화)"}')
    print(f'      {old}  →  {g}')
    if removed:
        print(f'      뺀 것: {removed}')
    if not ok:
        bad.append((name, w, g))
        print(f'      🔴 기대 {w}')
    print()

print('=' * 88)
print(f'  통과 {len(CASES)-len(bad)} / {len(CASES)}   ·  LLM 0회 (0원)')
for n, w, g in bad:
    print(f'    🔴 {n}: 기대 {w} / 실제 {g}')
print('=' * 88)
