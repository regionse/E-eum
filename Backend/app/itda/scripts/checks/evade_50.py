_MAP = {None: '통과', 'HARM': '2층', 'UNSAFE': '차단', 'SELFHARM': '위기안내',
        'VAGUE': '되묻기'}


def w(s):
    return sum(2 if ord(c) > 0x2E80 else 1 for c in str(s))


def pad(s, n):
    return str(s) + ' ' * max(1, n - w(s))


