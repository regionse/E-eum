def can_land(p):
    """착지 조건은 코드가 판정한다 — 모델의 자기보고(confidence)를 믿지 않는다.

    직업을 가리키는 세 축(관심분야·활동유형·다루는대상) 중 2개 이상이면 착지 가능.
    특정 슬롯을 필수로 못 박지 않는 이유: 모델이 "사람 돌보는 일"을 관심분야에 담기도,
    다루는대상+활동유형에 담기도 해서 — 못 박으면 같은 발화가 착지했다 말았다 한다(실측).
    2축 이상이면 '검색할 만큼은 안다'. (환경·시간·비용은 2026-07-28 제거)
    ※ 최소조건일 뿐 — 후보가 여러 갈래로 흩어지면 search 가 narrowing 으로 한 번 더 좁힌다.
    """
    p = p or {}
    return sum(1 for k in ('관심분야', '활동유형', '다루는대상') if p.get(k)) >= 2

def one_shot_land(p):
    """착지 조건이 **이번 턴 한 문장에서** 다 찼나 (2026-08-04).

    실측 사고 — 「빵 만드는 거 좋아해요」 한 문장에서
      관심분야=빵 · 활동유형=만들기 가 **동시에** 차서 그 자리에서 [제빵] 카드가 나갔다.
      조건은 찼지만 **대화를 한 적이 없다.** 좋아한다는 말 한 번은
      '이 사람이 그 일로 살아도 되겠다'의 근거가 못 된다.
    can_land 는 「2축이 찼나」만 보고 「몇 턴에 걸쳐 찼나」는 안 본다. 그 빈틈을 메운다.
    ※ 축이 하나라도 **이전 턴**에 채워져 있었으면 False — 그때는 서두르지 않은 것이다.
    ※ DIRECT(목표를 콕 집음)는 이 판정을 받지 않는다. 그건 바로 찾아준다.
    """
    p = p or {}
    st = p.get('_slot_turn') or {}
    now = int(p.get('_turns') or 0)
    axes = [k for k in ASK_ORDER if p.get(k)]
    if len(axes) < 2:
        return False
    return all(st.get(k) == now for k in axes)


