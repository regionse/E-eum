def pre_check(msg):
    """'VAGUE'=되묻기 / 'SELFHARM'=위기 안내(대화 유지) / 'UNSAFE'=차단 / None=정상"""
    msg = msg or ''
    meaningful = re.sub(r'[^가-힣a-zA-Z]', '', msg)
    #  ★ 자모만 있는 입력은 원래 전부 '무의미'로 봤다(「ㅁㄴㅇㄹ」 키보드 난타).
    #    그런데 **자모 축약은 실제로 쓰는 말이다** — 실측: 「ㅎㅇ」가 첫 마디였는데
    #    「잘 못 알아들었어요」로 차단됐다. 인사에 대고 못 알아들었다고 한 셈이다.
    #    자주 쓰는 축약만 통과시킨다(난타는 그대로 막힌다).
    _JAMO_OK = {'ㅎㅇ', 'ㅇㅇ', 'ㄴㄴ', 'ㄱㅅ', 'ㅇㅋ', 'ㅂㅂ', 'ㅅㄱ', 'ㅈㅅ'}
    _bare = re.sub(r'\s+', '', msg)
    if _bare in _JAMO_OK:
        return None
    if not meaningful or re.fullmatch(r'[ㄱ-ㅎㅏ-ㅣ\s]+', msg):
        return 'VAGUE'
    flat = msg.replace(' ', '')
    if any(b in flat for b in SELF_HARM):      # 자기 위해가 먼저다 — 욕설 판정보다 우선
        if not _is_career_not_crisis(flat):    # 단 '자살예방 상담사' 류는 진로 발화다(2026-08-04)
            return 'SELFHARM'
    if any(b in flat for b in HARM_OTHERS + ABUSE):
        return 'UNSAFE'
    return None


