def merge(old, new):
    """새로 파악한 슬롯만 덮어쓴다. 모델이 빠뜨려도 기존 값이 사라지지 않게.

    ★ 2026-08-04 — 리스트(관심대분류)는 예외로 **있으면 그대로 교체**한다.
      기존 규칙(빈 값이면 무시)을 그대로 두면 한 번 넓게 잡힌 분야가 영원히 안 좁혀진다.
      대화가 진행되면 ["기계","재료","건설"] → ["기계"] 로 **줄어들어야** 쓸모가 있는데,
      줄인 결과를 무시하면 슬롯이 늘어나기만 한다.
      (스칼라 슬롯의 '빠뜨려도 유지' 규칙은 그대로 둔다 — 모델이 매 턴 전부 다시 쓰지는 않는다.)
    """
    out = dict(old or {})
    for k, v in (new or {}).items():
        #  ★ 다중값 슬롯은 **쌓는다**(2026-08-04) — 덮어쓰면 앞서 들은 것이 밀려난다.
        #    실측: 1턴 활동유형=돕기·돌봄 → 3턴 활동유형=만들기 로 덮여 돌봄이 사라졌다.
        #    둘 다 사실이므로 둘 다 남긴다. 순서는 '먼저 들은 것'이 앞(중복 제거).
        if k in MULTI_SLOTS:
            cur = as_list(out.get(k))
            add = [x for x in as_list(v) if x]
            if add:
                out[k] = list(dict.fromkeys(cur + add))[:MULTI_MAX]
            continue
        if isinstance(v, list):
            out[k] = v
        elif v:
            out[k] = v
    return out

